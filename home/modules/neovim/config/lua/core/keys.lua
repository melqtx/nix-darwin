local function map(mode, key, action, desc, extra)
  vim.keymap.set(mode, key, action, vim.tbl_extend("force", { silent = true, desc = desc }, extra or {}))
end

-- Rex owns Ctrl/Alt+HJKL; leader chords always reach the editor.
for _, direction in ipairs({ "h", "j", "k", "l" }) do
  map("n", "<leader>w" .. direction, "<C-w>" .. direction, "Focus window " .. direction)
end
map("n", "<leader>wv", "<Cmd>vsplit<CR>", "Split window right")
map("n", "<leader>ws", "<Cmd>split<CR>", "Split window below")
map("n", "<leader>w=", "<C-w>=", "Balance windows")
map("n", "<leader>wq", "<Cmd>close<CR>", "Close window")
map("n", "<C-b>", "<Cmd>NvimTreeToggle<CR>", "Toggle file tree")
map("n", "<leader>e", "<Cmd>NvimTreeFindFileToggle<CR>", "Reveal file in tree")
map("n", "<leader>ff", "<Cmd>Telescope find_files<CR>", "Find project files")
map("n", "<leader>fr", "<Cmd>Telescope oldfiles<CR>", "Recent files")
map("n", "<leader>fg", "<Cmd>Telescope live_grep<CR>", "Search project text")
map("n", "<leader>fw", "<Cmd>Telescope grep_string<CR>", "Search word under cursor")
map("n", "<leader>fb", "<Cmd>Telescope buffers<CR>", "Find open buffers")
map("n", "<leader>fh", "<Cmd>Telescope help_tags<CR>", "Search help")
map("n", "<leader>?", "<Cmd>Telescope keymaps<CR>", "Search key bindings")
map("n", "<leader>fd", "<Cmd>Telescope diagnostics<CR>", "Project diagnostics")
map("n", "<leader>fs", "<Cmd>Telescope lsp_document_symbols<CR>", "Document symbols")
map("n", "<leader>cc", "gcc", "Toggle line comment", { remap = true })
map("x", "<leader>cc", "gc", "Toggle selection comment", { remap = true })
map("n", "<C-/>", "gcc", "Toggle line comment", { remap = true })
map("x", "<C-/>", "gc", "Toggle selection comment", { remap = true })
map("n", "<Esc>", "<Cmd>nohlsearch<CR>", "Clear search highlight")
map("n", "<leader>ww", "<Cmd>update<CR>", "Save file")
map("n", "<leader>bd", function()
  require("ui.buf.fn").close_buffer()
end, "Close buffer safely")
map("x", "<", "<gv", "Indent left and keep selection")
map("x", ">", ">gv", "Indent right and keep selection")
map("n", "<leader>t", "<Cmd>ToggleTerm<CR>", "Toggle terminal")
map("t", "<Esc><Esc>", "<C-\\><C-n>", "Leave terminal input mode")
map("n", "<leader>ol", "<Cmd>Lazy<CR>", "Plugin manager")
map("n", "<leader>ct", "<Cmd>PrismTelescope<CR>", "Pick editor theme")
map("n", "<leader>jj", function()
  require("core.jj").ui()
end, "Open jjui")
map("n", "<leader>js", function()
  require("core.jj").review({ "status" }, "text")
end, "JJ status")
map("n", "<leader>jd", function()
  require("core.jj").review({ "diff", "--git" }, "diff")
end, "JJ current change diff")
map("n", "<leader>jl", function()
  require("core.jj").review({ "log", "--limit", "20" }, "text")
end, "JJ history")
map("n", "<leader>jo", function()
  require("core.jj").review({ "op", "log", "--limit", "12" }, "text")
end, "JJ operation history")
map("n", "<leader>ld", vim.diagnostic.open_float, "Line diagnostics")
map("n", "[d", function()
  vim.diagnostic.jump({ count = -1, float = true })
end, "Previous diagnostic")
map("n", "]d", function()
  vim.diagnostic.jump({ count = 1, float = true })
end, "Next diagnostic")
